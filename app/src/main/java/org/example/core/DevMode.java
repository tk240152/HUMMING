package org.example.core;

/**
 * 開発用の機能をまとめて有効にするスイッチ。true にすると、遊ぶ人には見せない次のキーが効くようになる。
 * <pre>
 * P        : 次の画面へ進む（タイトル・ステージ選択以外）。ゲーム画面ではその時のタイムでクリアする（ベストタイムにも記録される）
 * F3       : ゲーム画面の数値を表示（表示中は 1〜6 で音量、M でミュート）
 * O        : 確認用の効果音を鳴らす（ゲーム画面）
 * R        : stage.json・ハチドリ・吸蜜エフェクトの設定を読み直す（ゲーム画面）／ベストタイムの表示をリセット（リザルト）
 * F2       : 詳細パネルの配置を編集する（ステージ選択）
 * </pre>
 * 配布するときは false にしておくこと。
 */
public final class DevMode {

    /** 開発用の機能を使うか（今はオフ。配布用） */
    public static final boolean ENABLED = false;

    private DevMode() {}
}
